function generateApiDocs(config: ProjectConfig): string {
  const lines: string[] = [`# API Documentation — ${config.projectName}`, ""];

  for (const ep of config.apiEndpoints) {
    if (!ep.crud) continue;
    lines.push(`## ${ep.table}`, "");
    lines.push(`### GET /functions/v1/${ep.table}`);
    lines.push(`List all ${ep.table}. Supports \`?page=1&limit=20\`.`, "");
    lines.push(`### POST /functions/v1/${ep.table}`);
    lines.push(`Create a new ${ep.table} record.`, "");
    lines.push(`### PUT /functions/v1/${ep.table}?id=<uuid>`);
    lines.push(`Update a ${ep.table} record.`, "");
    lines.push(`### DELETE /functions/v1/${ep.table}?id=<uuid>`);
    lines.push(`Delete a ${ep.table} record.`, "");
  }

  return lines.join("\n");
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
