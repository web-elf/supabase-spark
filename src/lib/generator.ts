function generateSeed(config: ProjectConfig): string {
  const lines: string[] = ["-- Seed Data", ""];
  for (const table of config.tables) {
    if (!table.name || table.columns.length === 0) continue;
    const cols = table.columns.filter((c) => !c.isPrimary && c.name !== "created_at" && c.name !== "updated_at" && c.name !== "deleted_at");
    if (cols.length === 0) continue;
    const colNames = cols.map((c) => c.name).join(", ");
    const sampleValues = cols.map((c) => {
      switch (c.type) {
        case "text": case "varchar": return `'sample_${c.name}'`;
        case "int": case "bigint": case "serial": case "bigserial": return "1";
        case "float": return "1.0";
        case "boolean": return "true";
        case "uuid": return "gen_random_uuid()";
        case "timestamp": case "timestamptz": case "date": return "now()";
        case "jsonb": case "json": return "'{}'";
        default: return "NULL";
      }
    }).join(", ");
    lines.push(`INSERT INTO public.${table.name} (${colNames}) VALUES (${sampleValues});`);
  }
  return lines.join("\n");
}

