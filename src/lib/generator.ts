// ─── Module: Rate Limiting ───────────────────────────────────────────────────

function generateRateLimitingModule(_config: ProjectConfig): GeneratedFile[] {
  const sql = `-- ============================================================
-- Module: Rate Limiting
-- SECURITY: Admin-only management of rate limit rules.
-- Users can only view their own request logs.
-- ============================================================

CREATE TABLE public.api_rate_limits (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  endpoint TEXT NOT NULL,
  max_requests INT NOT NULL DEFAULT 100,
  window_seconds INT NOT NULL DEFAULT 60,
  role TEXT DEFAULT 'authenticated',
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.api_rate_limits ENABLE ROW LEVEL SECURITY;

-- SECURITY: Only admins can configure rate limits
CREATE POLICY "Admins can manage rate limits"
  ON public.api_rate_limits FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Authenticated can read rate limits"
  ON public.api_rate_limits FOR SELECT TO authenticated
  USING (true);

CREATE TABLE public.request_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id),
  endpoint TEXT NOT NULL,
  ip_address INET,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.request_logs ENABLE ROW LEVEL SECURITY;

CREATE INDEX idx_request_logs_endpoint_created ON public.request_logs(endpoint, created_at);
CREATE INDEX idx_request_logs_ip_created ON public.request_logs(ip_address, created_at);
CREATE INDEX idx_request_logs_user_created ON public.request_logs(user_id, created_at);

-- SECURITY: Users can only see their own request logs
CREATE POLICY "Users can view own request logs"
  ON public.request_logs FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Admins can view all request logs"
  ON public.request_logs FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'));

-- Service role inserts request logs (from edge function)
CREATE POLICY "Service can insert request logs"
  ON public.request_logs FOR INSERT TO service_role
  WITH CHECK (true);

-- Cleanup function for old request logs
CREATE OR REPLACE FUNCTION public.cleanup_request_logs(retention_hours INT DEFAULT 24)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  DELETE FROM public.request_logs
  WHERE created_at < now() - (retention_hours || ' hours')::INTERVAL;
END;
$$;
`;

  const edgeFn = `import { serve } from "https://deno.land/std@0.168.0/http/server.ts"
import { createClient } from "https://esm.sh/@supabase/supabase-js@2"

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
}

/**
 * Rate Limiter Middleware
 * 
 * Usage: Call this function before processing a request to check
 * if the user/IP has exceeded their rate limit.
 * 
 * Returns 429 Too Many Requests with Retry-After header when exceeded.
 */
serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders })
  }

  const supabase = createClient(
    Deno.env.get('SUPABASE_URL')!,
    Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
  )

  try {
    const { endpoint, user_id, ip_address } = await req.json()

    // 1. Get rate limit config for this endpoint
    const { data: limitConfig } = await supabase
      .from('api_rate_limits')
      .select('*')
      .eq('endpoint', endpoint)
      .single()

    const maxRequests = limitConfig?.max_requests ?? 100
    const windowSeconds = limitConfig?.window_seconds ?? 60

    // 2. Count recent requests in the window
    const windowStart = new Date(Date.now() - windowSeconds * 1000).toISOString()

    let query = supabase
      .from('request_logs')
      .select('id', { count: 'exact' })
      .eq('endpoint', endpoint)
      .gte('created_at', windowStart)

    // Check by user_id first, then fall back to IP
    if (user_id) {
      query = query.eq('user_id', user_id)
    } else if (ip_address) {
      query = query.eq('ip_address', ip_address)
    }

    const { count } = await query

    // 3. Log this request
    await supabase.from('request_logs').insert({
      endpoint,
      user_id: user_id || null,
      ip_address: ip_address || null,
    })

    // 4. Check limit
    if ((count ?? 0) >= maxRequests) {
      return new Response(
        JSON.stringify({ error: 'Rate limit exceeded', retry_after: windowSeconds }),
        {
          status: 429,
          headers: {
            ...corsHeaders,
            'Content-Type': 'application/json',
            'Retry-After': String(windowSeconds),
          },
        }
      )
    }

    return new Response(
      JSON.stringify({ allowed: true, remaining: maxRequests - (count ?? 0) - 1 }),
      { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  } catch (error) {
    return new Response(JSON.stringify({ error: error.message }), {
      status: 500,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    })
  }
})
`;

  return [
    { path: "migrations/rate_limiting.sql", content: sql, category: "sql" },
    { path: "functions/rate-limiter/index.ts", content: edgeFn, category: "functions" },
  ];
}

// ─── Module: Multi-Tenancy ───────────────────────────────────────────────────

function generateMultiTenancyModule(config: ProjectConfig): GeneratedFile[] {
  let sql = `-- ============================================================
-- Module: Multi-Tenancy
-- SECURITY: Tenant isolation enforced via RLS.
-- organization_id column added to all user tables in core schema.
-- ============================================================

CREATE TABLE public.organizations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  owner_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  settings JSONB DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.organizations ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.organization_members (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  organization_id UUID REFERENCES public.organizations(id) ON DELETE CASCADE NOT NULL,
  role TEXT NOT NULL DEFAULT 'member',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(user_id, organization_id)
);

ALTER TABLE public.organization_members ENABLE ROW LEVEL SECURITY;

-- Helper: Check if the current user is a member of the given org
CREATE OR REPLACE FUNCTION public.is_tenant_member(_org_id UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.organization_members
    WHERE user_id = auth.uid() AND organization_id = _org_id
  )
$$;

-- Helper: Get the user's current organization (first org they belong to)
CREATE OR REPLACE FUNCTION public.current_organization()
RETURNS UUID LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT organization_id FROM public.organization_members
  WHERE user_id = auth.uid()
  LIMIT 1
$$;

-- RLS: Members can see their own organizations
CREATE POLICY "Members can view own orgs"
  ON public.organizations FOR SELECT TO authenticated
  USING (public.is_tenant_member(id));

-- RLS: Owners can manage their orgs
CREATE POLICY "Owners can manage orgs"
  ON public.organizations FOR ALL TO authenticated
  USING (owner_id = auth.uid());

-- RLS: Members can see their own memberships
CREATE POLICY "Members can view own memberships"
  ON public.organization_members FOR SELECT TO authenticated
  USING (user_id = auth.uid());

-- RLS: Org admins can manage members
CREATE POLICY "Org admins can manage members"
  ON public.organization_members FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.organization_members om
      WHERE om.user_id = auth.uid()
        AND om.organization_id = organization_id
        AND om.role = 'admin'
    )
  );
`;

  // Add foreign key from user tables to organizations
  for (const table of config.tables) {
    if (!table.name) continue;
    sql += `\n-- Tenant FK for ${table.name}`;
    sql += `\nALTER TABLE public.${table.name} ADD CONSTRAINT fk_${table.name}_org FOREIGN KEY (organization_id) REFERENCES public.organizations(id) ON DELETE CASCADE;`;
  }

  return [{ path: "migrations/multi_tenancy.sql", content: sql, category: "sql" }];
}

